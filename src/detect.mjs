import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

/** Run a command; never throws. */
export function sh(cmd, args, cwd, opts = {}) {
  const res = spawnSync(cmd, args, { cwd, encoding: 'utf8', ...opts });
  return {
    ok: !res.error && res.status === 0,
    status: res.status,
    missing: res.error?.code === 'ENOENT',
    out: (res.stdout || '').trim(),
    err: (res.stderr || '').trim() || res.error?.message || '',
  };
}

export const gitRoot = (dir) => {
  const r = sh('git', ['rev-parse', '--show-toplevel'], dir);
  return r.ok ? r.out : null;
};

/** The default branch: GitHub's, then origin/HEAD, then the current branch. */
export function detectBaseBranch(dir) {
  const gh = sh('gh', ['repo', 'view', '--json', 'defaultBranchRef', '--jq', '.defaultBranchRef.name'], dir);
  if (gh.ok && gh.out) return { branch: gh.out, source: 'GitHub' };
  const head = sh('git', ['symbolic-ref', '--short', 'refs/remotes/origin/HEAD'], dir);
  if (head.ok && head.out) return { branch: head.out.replace(/^origin\//, ''), source: 'origin/HEAD' };
  const cur = sh('git', ['branch', '--show-current'], dir);
  return { branch: cur.out || 'main', source: cur.out ? 'current branch' : 'fallback' };
}

/** A merge method the repo allows, preferring the reference default `merge`. */
export function detectMergeMethod(dir) {
  const r = sh('gh', ['api', 'repos/{owner}/{repo}', '--jq',
    '[.allow_merge_commit, .allow_squash_merge, .allow_rebase_merge] | @tsv'], dir);
  if (!r.ok) return null;
  const [merge, squash, rebase] = r.out.split('\t').map((v) => v === 'true');
  return merge ? 'merge' : squash ? 'squash' : rebase ? 'rebase' : null;
}

const INSTALLERS = [
  ['pnpm-lock.yaml', 'pnpm install --frozen-lockfile'],
  ['bun.lock', 'bun install --frozen-lockfile'],
  ['bun.lockb', 'bun install --frozen-lockfile'],
  ['yarn.lock', 'yarn install --frozen-lockfile'],
  ['package-lock.json', 'npm ci --prefer-offline --no-audit --no-fund'],
  ['npm-shrinkwrap.json', 'npm ci --prefer-offline --no-audit --no-fund'],
];

const STEPS = [
  ['lint', ['lint']],
  ['typecheck', ['typecheck', 'type-check', 'types', 'tsc', 'check-types']],
  ['test', ['test:ci', 'test']],
  ['build', ['build']],
];

// Scripts that would rewrite files or block: the gate must not run them.
const UNSAFE = /--fix\b|--write\b|--update-snapshots|\s-u\b|--watch\b|\bwatch\b/;

/**
 * Build checks.sh from package.json scripts. Returns null when there's nothing
 * safe to run, so the placeholder stays and /factory-setup fills it in.
 */
export function generateChecks(dir) {
  const pkgPath = join(dir, 'package.json');
  if (!existsSync(pkgPath)) return null;
  let scripts;
  try {
    scripts = JSON.parse(readFileSync(pkgPath, 'utf8')).scripts || {};
  } catch {
    return null;
  }
  const install = INSTALLERS.find(([lock]) => existsSync(join(dir, lock)));
  const runner = install ? install[1].split(' ')[0] : 'npm';
  const run = (name) => (runner === 'npm' ? `npm run ${name}` : `${runner} run ${name}`);

  const lines = [];
  const skipped = [];
  for (const [, candidates] of STEPS) {
    const name = candidates.find((c) => scripts[c]);
    if (!name) continue;
    if (UNSAFE.test(scripts[name]) || /^echo .*no test specified/i.test(scripts[name])) {
      skipped.push(`${name}: ${scripts[name]}`);
      continue;
    }
    lines.push(run(name));
  }
  if (!lines.length) return null;

  const body = [
    '#!/usr/bin/env bash',
    "# The repo's checks. Exit 0 only when the branch is fit to review.",
    '#',
    "# The gate runs this script from the main checkout with the job's worktree as",
    '# the working directory. Keep it fast, deterministic and non-interactive: no',
    '# watch modes, no prompts, nothing that rewrites files.',
    '#',
    '# Generated by `agent-factory init` from package.json scripts. Review it, then',
    '# run /factory-setup in Claude Code to finish tailoring the factory.',
    ...(skipped.length
      ? ['#', '# Skipped because they would rewrite files or block:', ...skipped.map((s) => `#   ${s}`)]
      : []),
    'set -euo pipefail',
    '',
    '# Test runners such as Vitest and Jest skip watch mode under CI.',
    'export CI=true',
    '',
    install ? install[1] : 'npm install --no-audit --no-fund',
    ...lines,
    '',
  ];
  return { content: body.join('\n'), commands: [install?.[1] ?? 'npm install', ...lines], skipped };
}

/** Parse "2.1.257 (Claude Code)" or "Python 3.12.8" into [major, minor, patch]. */
export function parseVersion(s) {
  const m = String(s).match(/(\d+)\.(\d+)(?:\.(\d+))?/);
  return m ? [Number(m[1]), Number(m[2]), Number(m[3] || 0)] : null;
}

export function versionAtLeast(have, want) {
  for (let i = 0; i < 3; i++) {
    if (have[i] !== want[i]) return have[i] > want[i];
  }
  return true;
}
